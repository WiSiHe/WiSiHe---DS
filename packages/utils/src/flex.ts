/**
 * CSS flex-direction values for flexbox layouts.
 */
export type FlexDirection = 'row' | 'row-reverse' | 'column' | 'column-reverse';

/**
 * CSS flex-wrap values for flexbox layouts.
 */
export type FlexWrap = 'nowrap' | 'wrap' | 'wrap-reverse';

/**
 * CSS justify-content values for flexbox layouts.
 */
export type JustifyContent =
  | 'flex-start'
  | 'flex-end'
  | 'center'
  | 'space-between'
  | 'space-around'
  | 'space-evenly';
